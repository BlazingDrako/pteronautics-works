#!/usr/bin/env bash
# Re-copy the solver core from a local Pteronautics Atlas checkout into core/.
#
#   scripts/sync-core.sh [path-to-atlas]      (default: ../Pteronautics)
#
# What it copies:
#   <atlas>/js/solvers/            -> core/solvers/      (all solvers, including mfoil/)
#   <atlas>/js/lib/<needed>.js     -> core/lib/          (only the helpers the solvers import)
#   <atlas>/tests/*.tests.js       -> tests/core/        (only tests that need nothing outside the solvers;
#                                                         import paths rewritten from ../js/ to ../../core/)
# and records the Atlas commit in core/SOURCE.md. The solver files are never edited here: if Works needs a
# different interface, wrap the solver in src/adapters/.
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
ATLAS="$(cd "${1:-$HERE/../Pteronautics}" && pwd)"
[ -d "$ATLAS/js/solvers" ] || { echo "No js/solvers in $ATLAS: pass the path to an Atlas checkout" >&2; exit 1; }

COMMIT="$(git -C "$ATLAS" rev-parse HEAD)"
SUBJECT="$(git -C "$ATLAS" log -1 --format=%s)"
DATE="$(git -C "$ATLAS" log -1 --format=%cs)"
DIRTY=""
if [ -n "$(git -C "$ATLAS" status --porcelain -- js/solvers js/lib tests)" ]; then
  DIRTY=" (with uncommitted changes in js/solvers, js/lib or tests)"
  echo "warning: Atlas has uncommitted changes under js/solvers, js/lib or tests" >&2
fi

rm -rf "$HERE/core/solvers" "$HERE/core/lib" "$HERE/tests/core"
mkdir -p "$HERE/core/lib" "$HERE/tests/core"
cp -R "$ATLAS/js/solvers" "$HERE/core/solvers"

# helpers the solvers import from ../lib/ or ../../lib/
LIBS="$(grep -rhoE "from '(\.\./)+lib/[A-Za-z0-9_]+\.js'" "$HERE/core/solvers" | sed -E "s#.*lib/([A-Za-z0-9_]+\.js)'#\1#" | sort -u)"
for f in $LIBS; do cp "$ATLAS/js/lib/$f" "$HERE/core/lib/$f"; done
# helpers can import each other
for f in $LIBS; do
  for g in $(grep -hoE "from '\./[A-Za-z0-9_]+\.js'" "$ATLAS/js/lib/$f" | sed -E "s#from '\./##; s#'##"); do
    [ -f "$HERE/core/lib/$g" ] || cp "$ATLAS/js/lib/$g" "$HERE/core/lib/$g"
  done
done

# tests that only reach into js/solvers and js/lib (the rest test Atlas's UI modules)
COPIED=(); SKIPPED=()
for t in "$ATLAS"/tests/*.tests.js; do
  name="$(basename "$t")"
  if grep -qE "from '\.\./js/(modules|app|previews)" "$t"; then SKIPPED+=("$name"); continue; fi
  sed -e "s#'\.\./js/solvers/#'../../core/solvers/#g" -e "s#'\.\./js/lib/#'../../core/lib/#g" "$t" > "$HERE/tests/core/$name"
  COPIED+=("$name")
done

# an index the Works test page imports: every exported *Tests function of the copied files
{
  echo "// Generated by scripts/sync-core.sh: the Atlas solver tests copied into Works."
  for n in "${COPIED[@]}"; do echo "export * from './$n';"; done
} > "$HERE/tests/core/index.js"

{
  echo "# Solver core source"
  echo
  echo "\`core/\` is a recorded snapshot of the solvers from **Pteronautics Atlas** (GPL-3.0, copyright Andrew Aguiar)."
  echo "Do not edit these files in place: re-sync with \`scripts/sync-core.sh\`, and wrap any interface Works needs in \`src/adapters/\`."
  echo
  echo "- Atlas commit: \`$COMMIT\`$DIRTY"
  echo "- Commit subject: $SUBJECT"
  echo "- Commit date: $DATE"
  echo "- Synced: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo
  echo "## Copied"
  echo
  echo "- \`js/solvers/\` → \`core/solvers/\` ($(find "$HERE/core/solvers" -name '*.js' | wc -l | tr -d ' ') files, including \`mfoil/\`, MIT, see \`LICENSE-mfoil.txt\`)"
  echo "- \`js/lib/\` → \`core/lib/\`: $(echo $LIBS $(ls "$HERE/core/lib") | tr ' ' '\n' | sort -u | tr '\n' ' ')"
  echo "- Tests → \`tests/core/\` (import paths rewritten): ${COPIED[*]}"
  echo
  echo "## Not copied"
  echo
  echo "Tests that import Atlas UI modules (\`js/modules/\`), so they cannot run without the Atlas app: ${SKIPPED[*]}."
  echo "The mfoil checks inside Atlas's \`tests/tests.js\` runner are also not copied, since that runner imports those tests."
} > "$HERE/core/SOURCE.md"

echo "Synced core from $ATLAS @ ${COMMIT:0:10}: ${#COPIED[@]} test files copied, ${#SKIPPED[@]} skipped"
